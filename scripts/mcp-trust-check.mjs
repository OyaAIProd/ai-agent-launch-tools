#!/usr/bin/env node

const CHECKS = [
  {
    id: "identity",
    title: "Server identity",
    criteria: [
      "Publisher is known and expected.",
      "Repository, package, binary, or deployment source matches the publisher claim.",
      "Install and update path cannot silently switch source, host, or package scope.",
      "Rollback owner and disable path are documented.",
    ],
  },
  {
    id: "manifest",
    title: "Manifest and schema review",
    criteria: [
      "Tool names, descriptions, schemas, enum values, and examples are reviewed before first use.",
      "New or changed tools default to ask or deny until reviewed.",
      "Descriptions and schemas cannot override system, developer, operator, or workflow policy.",
      "Arguments expose destination, side-effect class, data class, and external-send behavior.",
    ],
  },
  {
    id: "actions",
    title: "Action classification",
    criteria: [
      "Each tool is classified as read_public, read_private, write_record, execute_code, or credential_or_permission.",
      "Read_private tools have data-boundary and redaction expectations.",
      "Write, execute, credential, identity, financial, tax, bank, payout, and permission actions require explicit approval.",
      "Missing policy, redactor, approval UI, or receipt writer fails closed.",
    ],
  },
  {
    id: "approval",
    title: "Approval gates",
    criteria: [
      "First invocation shows server, tool name, action class, destination, arguments, and data classes involved.",
      "Untrusted content involvement is visible before approval.",
      "Remembered approval is narrow and revocable.",
      "Untrusted content cannot grant approval or widen an approval rule.",
    ],
  },
  {
    id: "fixtures",
    title: "Prompt-injection fixtures",
    criteria: [
      "Tool output attempts to instruct a later tool call.",
      "Retrieved docs attempt to expose secrets or widen permissions.",
      "Tool metadata attempts to convince the reviewer or model that the server is safe.",
      "Stored state attempts to trigger a delayed future action.",
    ],
  },
  {
    id: "evidence",
    title: "Redacted evidence",
    criteria: [
      "Receipt includes server/tool label, reviewed source, action class, approval decision, rationale, denied tools, redaction result, fixture id, and rollback owner.",
      "Receipt excludes secrets, tokens, API keys, cookies, OAuth codes, passwords, private screenshots, customer records, buyer data, payment data, full names, private handles, card, bank, tax, payout, and full transaction identifiers.",
      "Evidence is safe to paste into a public issue or launch note after review.",
    ],
  },
];

function usage() {
  return [
    "Usage: mcp-trust-check [options]",
    "",
    "Generates a non-sensitive MCP trust verification plan.",
    "",
    "Options:",
    "  --server <label>       Server or tool label.",
    "  --workflow <summary>   High-level workflow boundary.",
    "  --json                 Print structured JSON.",
    "  --markdown             Print Markdown. Default.",
    "  --help                 Show this help.",
    "",
    "Do not pass secrets, tokens, private endpoints, customer records, payment data,",
    "private screenshots, full names, private handles, or transaction identifiers.",
  ].join("\n");
}

function readOption(args, name, fallback) {
  const index = args.indexOf(name);
  if (index === -1) return fallback;
  const value = args[index + 1];
  if (!value || value.startsWith("--")) {
    throw new Error(`${name} requires a value.`);
  }
  return value;
}

function hasSensitiveShape(text) {
  return [
    /\b[\w.+-]+@[\w-]+\.[\w.-]+\b/i,
    /\b(?:sk|rk|pk)_(?:live|test)_[A-Za-z0-9_]{12,}\b/,
    /\b(?:api[_ -]?key|oauth|bearer|password|secret|token)\b\s*[:=]/i,
    /\b(?:\d[ -]*?){13,19}\b/,
  ].some((pattern) => pattern.test(text));
}

function buildPlan({ server, workflow }) {
  return {
    ok: true,
    server,
    workflow,
    generatedBy: "ai-agent-launch-tools mcp-trust-check",
    checks: CHECKS,
    launchDecision: [
      "Approve only when server identity, manifest review, action classification, approval gates, prompt-injection fixtures, and redacted evidence are complete.",
      "If server or tool behavior is ambiguous, default to ask or deny and keep the tool unavailable to autonomous runs.",
    ],
    publicGenerator: "https://ai-launch-risk-check-public.vercel.app/mcp-trust-verification-generator.html",
    paidPack: "https://ai-launch-risk-check-public.vercel.app/",
  };
}

function printMarkdown(plan) {
  console.log("# MCP Trust Verification Plan");
  console.log("");
  console.log(`- Server/tool label: ${plan.server}`);
  console.log(`- Workflow boundary: ${plan.workflow}`);
  console.log(`- Generated by: ${plan.generatedBy}`);
  console.log("");

  for (const section of plan.checks) {
    console.log(`## ${section.title}`);
    console.log("");
    for (const criterion of section.criteria) {
      console.log(`- [ ] ${criterion}`);
    }
    console.log("");
  }

  console.log("## Launch Decision");
  console.log("");
  for (const item of plan.launchDecision) {
    console.log(`- ${item}`);
  }
  console.log("");
  console.log("## Links");
  console.log("");
  console.log(`- Browser generator: ${plan.publicGenerator}`);
  console.log(`- Full launch pack: ${plan.paidPack}`);
}

function main() {
  const args = process.argv.slice(2);
  if (args.includes("--help") || args.includes("-h")) {
    console.log(usage());
    return 0;
  }

  const json = args.includes("--json");
  const markdown = args.includes("--markdown");
  if (json && markdown) {
    console.error("Error: use either --json or --markdown, not both.");
    return 1;
  }

  let server;
  let workflow;
  try {
    server = readOption(args, "--server", "candidate MCP server");
    workflow = readOption(args, "--workflow", "one AI workflow that can read docs and call approved tools");
  } catch (error) {
    console.error(`Error: ${error instanceof Error ? error.message : String(error)}`);
    return 1;
  }

  const combined = `${server}\n${workflow}`;
  if (hasSensitiveShape(combined)) {
    console.error("Error: input looks sensitive. Use high-level placeholders only.");
    return 1;
  }

  const plan = buildPlan({ server, workflow });
  if (json) console.log(JSON.stringify(plan, null, 2));
  else printMarkdown(plan);
  return 0;
}

process.exitCode = main();
